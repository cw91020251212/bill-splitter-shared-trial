import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const assets = [
  ['index.html', 'text/html; charset=utf-8'],
  ['app.js', 'text/javascript; charset=utf-8'],
  ['style.css', 'text/css; charset=utf-8'],
  ['service-worker.js', 'text/javascript; charset=utf-8'],
  ['manifest.webmanifest', 'application/manifest+json; charset=utf-8'],
  ['icon.png', 'image/png'],
  ['icon.svg', 'image/svg+xml; charset=utf-8'],
];

const entries = {};
for (const [name, contentType] of assets) {
  const bytes = readFileSync(resolve(root, 'public', name));
  entries[`/${name}`] = contentType === 'image/png'
    ? { contentType, base64: bytes.toString('base64') }
    : { contentType, text: bytes.toString('utf8') };
}

const output = resolve(root, 'worker', 'static-assets.js');
const source = `// Generated by scripts/build-worker-assets.mjs; contains public assets only.\nexport const STATIC_ASSETS = ${JSON.stringify(entries)};\n`;
writeFileSync(output, source, 'utf8');
const byteCount = Object.values(entries).reduce((sum, asset) => sum + (asset.text?.length || asset.base64?.length || 0), 0);
console.log(`Bundled ${assets.length} public assets (${byteCount} text/base64 characters).`);
